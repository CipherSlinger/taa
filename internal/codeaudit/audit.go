// ── Core aggregation functions ────────────────────────────

// GroupFindingsByFile groups findings by their file path.
func GroupFindingsByFile(findings []Finding) map[string][]Finding {
	groups := make(map[string][]Finding)
	for _, f := range findings {
		groups[f.File] = append(groups[f.File], f)
	}
	return groups
}

// BuildFileReport constructs a FileReport from findings (Go-computed fields only).
// LLM fields (RiskLevel, Summary, Chained, HasExfiltrationPattern) are left empty
// and should be filled by analyzeFileWithLLM.
func BuildFileReport(filePath string, findings []Finding) FileReport {
	highCount := 0
	mediumCount := 0
	for _, f := range findings {
		switch f.Severity {
		case SeverityHigh:
			highCount++
		case SeverityMedium:
			mediumCount++
		}
	}

	fr := FileReport{
		File:            filepath.Base(filePath),
		FilePath:        filePath,
		FindingsCount:  len(findings),
		HighCount:      highCount,
		MediumCount:    mediumCount,
		Findings:       findings,
	}

	// If no LLM, infer risk level from static data.
	fr.RiskLevel = InferRiskLevel(highCount, mediumCount)
	fr.Summary = "仅静态扫描，未进行语义分析"

	return fr
}

// InferRiskLevel determines risk level from static finding counts.
func InferRiskLevel(highCount, mediumCount int) string {
	if highCount > 0 {
		return "HIGH"
	}
	if mediumCount > 0 {
		return "MEDIUM"
	}
	return "LOW"
}

// isTestFile returns true if the file path indicates a test script, helper, or fixture.
func isTestFile(path string) bool {
	if path == "" {
		return false
	}
	base := strings.ToLower(filepath.Base(path))
	if strings.HasPrefix(base, "test_") || strings.HasSuffix(base, "_test.py") || strings.HasSuffix(base, "_test.go") {
		return true
	}
	cleaned := filepath.ToSlash(strings.ToLower(path))
	if strings.Contains(cleaned, "/tests/") || strings.Contains(cleaned, "/test/") ||
		strings.HasPrefix(cleaned, "tests/") || strings.HasPrefix(cleaned, "test/") {
		return true
	}
	return false
}

// ClassifyFindingRisk determines the final risk level (HIGH, MEDIUM, LOW) of a finding,
// prioritized by the LLM's evaluation and falling back to static scan severity.
func ClassifyFindingRisk(f Finding) string {
	switch strings.ToUpper(strings.TrimSpace(f.LLMRisk)) {
	case "HIGH", "CRITICAL":
		return "HIGH"
	case "MEDIUM":
		return "MEDIUM"
	case "LOW", "NONE":
		return "LOW"
	}

	switch strings.ToUpper(strings.TrimSpace(f.LLMVerdict)) {
	case "MALICIOUS":
		return "HIGH"
	case "SUSPICIOUS":
		return "MEDIUM"
	case "BENIGN":
		return "LOW"
	case "UNCERTAIN":
		if f.Severity == SeverityHigh {
			return "HIGH"
		}
		// Benign metadata logging or findings located in test fixtures are downgraded to LOW when uncertain.
		if f.RuleID == "EMB_003" || isTestFile(f.File) {
			return "LOW"
		}
		return "MEDIUM"
	}

	switch f.Severity {
	case SeverityHigh:
		return "HIGH"
	case SeverityMedium:
		// Benign metadata logging or findings located in test fixtures are downgraded to LOW in static fallback.
		if f.RuleID == "EMB_003" || isTestFile(f.File) {
			return "LOW"
		}
		return "MEDIUM"
	default:
		return "LOW"
	}
}

// ComputeStatistics aggregates finding counts categorized into high, medium, low by LLM evaluation.
func ComputeStatistics(findings []Finding) AuditStatistics {
	stats := AuditStatistics{}
	for _, f := range findings {
		switch ClassifyFindingRisk(f) {
		case "HIGH":
			stats.High++
		case "MEDIUM":
			stats.Medium++
		case "LOW":
			stats.Low++
		}
		if f.IsCrossFile {
			stats.CrossFile++
		}
		if f.IsMicroservice {
			stats.Microservice++
		}
	}
	return stats
}

// ConclusionContext carries additional audit context for conclusion generation.
type ConclusionContext struct {
	LLMDegraded  bool
	HasLLMBenign bool
	ScanPassed   *bool
	FailClosed   bool
}

// ComputeConclusion determines the audit conclusion from statistics and policy.
// Retained for backward compatibility.
func ComputeConclusion(stats AuditStatistics, fileReports []FileReport, policy string) AuditConclusion {
	return ComputeConclusionContext(stats, fileReports, policy, ConclusionContext{
		HasLLMBenign: true,
	})
}

// ComputeConclusionContext determines the audit conclusion from statistics, policy, and scan context.
func ComputeConclusionContext(stats AuditStatistics, fileReports []FileReport, policy string, ctx ConclusionContext) AuditConclusion {
	riskLevel := "NONE"

	if stats.High > 0 {
		riskLevel = "CRITICAL"
	} else if stats.Medium > 0 {
		riskLevel = "MEDIUM"
	} else if stats.Low > 0 {
		riskLevel = "LOW"
	}

	var passed bool
	switch policy {
	case "gate":
		// Gate mode: block on High and Medium risk findings. Low (benign) findings pass.
		passed = stats.High == 0 && stats.Medium == 0
	default:
		// Assist mode (default): block on High risk findings.
		passed = stats.High == 0
	}

	if ctx.ScanPassed != nil && !*ctx.ScanPassed {
		passed = false
	}

	summary := buildSummaryTextExt(stats, riskLevel, passed, ctx.LLMDegraded, ctx.HasLLMBenign)
	recommendation := buildRecommendation(fileReports)

	return AuditConclusion{
		Passed:         passed,
		RiskLevel:      riskLevel,
		Summary:        summary,
		Recommendation: recommendation,
		Statistics:     stats,
	}
}

// ── Report assembly ───────────────────────────────────────

// AssembleAuditReport combines all components into the final AuditReport.
func AssembleAuditReport(
	dir string,
	scanReport *Report,
	fileReports []FileReport,
	fileLineCounts map[string]int,
	cfg LLMConfig,
	duration time.Duration,
) *AuditReport {
	stats := ComputeStatistics(scanReport.Findings)

	sortFileReports(fileReports)

	var hasLLMBenign bool
	var scanPassed *bool
	var llmDegraded bool
	if scanReport != nil {
		// ScanPassed is the channel that forces failure under both policies, so
		// it carries the completeness precondition as well as the finding-based
		// decision. Without it a scan that dropped findings, or never finished,
		// would reach ComputeConclusionContext as a pass and the only trace of
		// the unexamined input would be a metadata field nobody reads.
		sp := scanReport.Passed && scanReport.ProvesCleanScan()
		scanPassed = &sp
		llmDegraded = scanReport.LLMDegraded
		for _, f := range scanReport.Findings {
			if strings.EqualFold(strings.TrimSpace(f.LLMVerdict), "BENIGN") {
				hasLLMBenign = true
				break
			}
		}
	}

	conclusion := ComputeConclusionContext(stats, fileReports, cfg.Policy, ConclusionContext{
		LLMDegraded:  llmDegraded,
		HasLLMBenign: hasLLMBenign,
		ScanPassed:   scanPassed,
		FailClosed:   cfg.FailClosed,
	})

	totalLines := 0
	for _, count := range fileLineCounts {
		totalLines += count
	}

	// Provenance and completeness travel with the report, so that a reader can
	// tell a complete scan from a partial one without treating the absence of
	// evidence as evidence of absence.
	var (
		engine          string
		engineVersion   string
		scanComplete    bool
		parserErrors    int
		truncated       bool
		unsupportedExts int
		processExitCode int
	)
	if scanReport != nil {
		engine = scanReport.Engine
		engineVersion = scanReport.EngineVersion
		scanComplete = scanReport.ScanComplete
		parserErrors = scanReport.ParserErrors
		truncated = scanReport.Truncated
		unsupportedExts = scanReport.UnsupportedExts
		processExitCode = scanReport.ProcessExitCode
	}

	return &AuditReport{
		ReportID:  GenerateReportID(),
		AuditTime: time.Now().Format(time.RFC3339),
		Target: AuditTarget{
			Directory:         dir,
			FilesScanned:      scanReport.FilesCount,
			TotalLines:        totalLines,
			FilesWithFindings: len(fileReports),
		},
		Conclusion: conclusion,
		Statistics: stats,
		FileReports: fileReports,
		ScanMetadata: AuditMetadata{
			ScannerVersion: "1.0.0",
			RulesCount:     len(DefaultRules()),
			LLMModel:       cfg.Model,
			LLMEnabled:     cfg.Enabled,
			Policy:         cfg.Policy,
			ScanDurationMs: duration.Milliseconds(),
			LLMDegraded:    scanReport != nil && scanReport.LLMDegraded,

			Engine:          engine,
			EngineVersion:   engineVersion,
			ScanComplete:    scanComplete,
			ParserErrors:    parserErrors,
			Truncated:       truncated,
			UnsupportedExts: unsupportedExts,
			ProcessExitCode: processExitCode,
		},
	}
}

// ── Helper functions ──────────────────────────────────────

// GenerateReportID creates a unique audit report identifier.
func GenerateReportID() string {
	ts := time.Now().Format("20060102-150405")
	b := make([]byte, 4)
	_, _ = rand.Read(b)
	return fmt.Sprintf("audit-%s-%x", ts, b)
}

// BuildFindingsSummary creates a compact summary of findings for the LLM prompt.
// e.g. "NET_001(网络请求,HIGH), CMD_001(命令执行,HIGH)"
func BuildFindingsSummary(findings []Finding) string {
	if len(findings) == 0 {
		return "无"
	}
	parts := make([]string, 0, len(findings))
	seen := make(map[string]bool)
	for _, f := range findings {
		key := f.RuleID
		if seen[key] {
			continue
		}
		seen[key] = true
		parts = append(parts, fmt.Sprintf("%s(%s,%s)", f.RuleID, f.Category, f.Severity))
	}
	return strings.Join(parts, ", ")
}

// ReadFileForAnalysis reads a source file and returns up to maxLines lines.
func ReadFileForAnalysis(path string, maxLines int) string {
	f, err := os.Open(path)
	if err != nil {
		return "// 无法读取文件"
	}
	defer f.Close()

	var lines []string
	scanner := bufio.NewScanner(f)
	for scanner.Scan() && len(lines) < maxLines {
		lines = append(lines, scanner.Text())
	}

	if len(lines) == 0 {
		return "// 文件为空"
	}

	code := strings.Join(lines, "\n")
	if scanner.Scan() {
		// More lines exist — add truncation notice.
		code += fmt.Sprintf("\n// ... (截断，文件超过 %d 行)", maxLines)
	}
	return code
}

// CountFileLines returns the number of lines in a file.
func CountFileLines(path string) int {
	f, err := os.Open(path)
	if err != nil {
		return 0
	}
	defer f.Close()

	count := 0
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		count++
	}
	return count
}

// ── Internal helpers ──────────────────────────────────────

func buildSummaryText(stats AuditStatistics, riskLevel string) string {
	passed := riskLevel != "CRITICAL" && riskLevel != "HIGH"
	return buildSummaryTextExt(stats, riskLevel, passed, false, true)
}

func buildSummaryTextExt(stats AuditStatistics, riskLevel string, passed bool, llmDegraded bool, hasLLMBenign bool) string {
	if stats.Total() == 0 {
		return "未发现安全问题，代码通过审计"
	}

	parts := []string{}
	if stats.High > 0 {
		parts = append(parts, fmt.Sprintf("发现 %d 处高危风险代码", stats.High))
	}
	if stats.Medium > 0 {
		parts = append(parts, fmt.Sprintf("发现 %d 处中危风险代码", stats.Medium))
	}
	if stats.Low > 0 {
		if len(parts) > 0 {
			parts = append(parts, fmt.Sprintf("%d 处低危/良性提示项", stats.Low))
		} else if llmDegraded {
			parts = append(parts, fmt.Sprintf("发现 %d 处低危/良性提示项（大模型服务降级，按规则评估）", stats.Low))
		} else if hasLLMBenign {
			parts = append(parts, fmt.Sprintf("发现 %d 处低危/良性提示项（大模型确认为正常）", stats.Low))
		} else {
			parts = append(parts, fmt.Sprintf("发现 %d 处低危/良性提示项", stats.Low))
		}
	}

	if len(parts) == 0 {
		return fmt.Sprintf("发现 %d 处安全提示项", stats.Total())
	}

	summary := "审计结论: " + strings.Join(parts, "，")

	if !passed {
		if riskLevel == "CRITICAL" || riskLevel == "HIGH" {
			summary += "。存在数据泄露风险，建议阻断导入"
		} else {
			summary += "。触发 fail-closed 阻断策略，禁止导入"
		}
	} else if riskLevel == "CRITICAL" || riskLevel == "HIGH" {
		summary += "。存在数据泄露风险，建议阻断导入"
	} else if riskLevel == "LOW" || riskLevel == "NONE" {
		summary += "。代码符合安全规范，准予导入"
	}
	return summary
}

func buildRecommendation(fileReports []FileReport) string {
	// Collect unique rule IDs from high/medium risk findings.
	ruleIDs := make(map[string]bool)
	for _, fr := range fileReports {
		for _, f := range fr.Findings {
			risk := ClassifyFindingRisk(f)
			if risk == "HIGH" || risk == "MEDIUM" {
				ruleIDs[f.RuleID] = true
			}
		}
	}

	if len(ruleIDs) == 0 {
		return "无需修复"
	}

	var suggestions []string
	for ruleID := range ruleIDs {
		s := SuggestionForRule(ruleID)
		suggestions = append(suggestions, fmt.Sprintf("%s: %s", ruleID, s))
	}
	sort.Strings(suggestions)

	return "建议修复: " + strings.Join(suggestions, "; ")
}

// sortFileReports orders the file reports for the report that leaves the process:
// highest risk first, then most findings, then path.
//
// The order has to be total, not merely plausible. The reports arrive from a map
// iteration in GenerateAuditReport, so a comparator that leaves ties unresolved
// hands the run's ordering back to the map seed, and two audits of the same code
// emit file_reports in different orders. Anyone diffing, hashing or eyeballing two
// reports is then reading noise.
//
// The final key is FilePath rather than File: File is a base name, and two files
// in different directories — src/model.py and tests/model.py — would collide on
// it, leaving exactly the tie this key exists to break.
func sortFileReports(fileReports []FileReport) {
	sort.Slice(fileReports, func(i, j int) bool {
		ri, rj := riskOrder(fileReports[i].RiskLevel), riskOrder(fileReports[j].RiskLevel)
		if ri != rj {
			return ri < rj // lower order = higher risk, comes first
		}
		if fileReports[i].FindingsCount != fileReports[j].FindingsCount {
			return fileReports[i].FindingsCount > fileReports[j].FindingsCount
		}
		return fileReports[i].FilePath < fileReports[j].FilePath
	})
}

func riskOrder(level string) int {
	switch level {
	case "CRITICAL":
		return 0
	case "HIGH":
		return 1
	case "MEDIUM":
		return 2
	case "LOW":
		return 3
	case "NONE":
		return 4
	default:
		return 5
	}
}

// MergeBinaryFindings folds one binary pass into the scan report that the LLM
// and the conclusion read.
//
// It is a merge rather than a second report because everything downstream - the
// finding-level verifier, the file grouping, the risk classification, the
// statistics, the recommendation - is written against one finding list. A
// parallel list would be a second implementation of each of them, and the two
// would answer differently the first time one was changed.
//
// Three things happen, and the order matters:
//
//  1. The binary summary is attached first, because recomputeReportPassed below
//     reads it through ProvesCleanScan, and a summary attached after the
//     recomputation would leave the pass decision computed without it.
//  2. The text findings of files the binary channel claimed are dropped. A file
//     whose bytes are binary is not a file whose text reading means anything,
//     and keeping that reading would put findings in the report that no one can
//     act on - while letting a crafted file choose how many of them there are.
//  3. The static counts are recomputed from the joined list. Recomputing rather
//     than adjusting is what keeps Passed, HighCount and MediumCount consistent
//     with the findings they describe.
//
// There is deliberately no cap on the joined list, and no second truncation.
// Each channel capped its own findings before this ran - the source arm at
// Config.MaxFindings, the binary arm at BinaryConfig.MaxFindings - and
// reapplying one ceiling to the sum would couple them in the one direction that
// costs a model package. A shared ceiling would let a large source arm evict
// binary findings by path order, and it would choose which findings to drop by
// path order rather than by importance.
//
// Nothing here sets Report.Truncated, and that is a decision rather than an
// omission. Report.Truncated is the completeness flag the report copies into
// scan_metadata.truncated, and ProvesCleanScan refuses on it: a merge that set
// it from the binary arm's own cap would make the channel delete a package for
// having found too much. The cap drops LOW findings and only LOW (see
// BinaryScanner.ScanDirectory), and LOW blocks under neither the `assist` nor the
// `gate` policy - the two severities that can block, HIGH and MEDIUM, are kept
// whatever the budget - so nothing the cap drops could have blocked the import on
// its own. A reader who wants the binary cap sees findings_capped and
// findings_dropped in scan_metadata.binary, next to the max_findings it ran
// under; what they must not see is a completeness flag that claims a look did not
// happen when it did.
//
// This is the only place the binary channel touches any completeness field on
// Report, which is worth stating because the other five - ScanComplete,
// Truncated, ParserErrors, UnsupportedExts and ProcessExitCode - are the source
// arm's and are read by ProvesCleanScan as such. The binary channel's own gaps
// travel on Report.Binary and are folded by that method; none of them is written
// here.
func MergeBinaryFindings(report *Report, res *BinaryScanResult) {
	if report == nil || res == nil {
		return
	}

	report.Binary = &res.Summary

	// The binary files are added to the count the report states as scanned.
	// AssembleAuditReport copies this field into Target.FilesScanned, and leaving
	// it at the source arm's total would put a number in target.files_scanned that
	// contradicts scan_metadata.binary.files_count in the same document, where the
	// lower of the two is the one a reader would believe.
	//
	// The sum is not an exact count of distinct files: the two arms count by
	// different criteria, so a file can be counted twice. The source arm counts by
	// extension - a path whose extension is not in its set is skipped without
	// being opened (scanner.go:86-88, scanner.go:280-282) - while this channel
	// counts by content, so a file with a scannable extension whose bytes are
	// binary is read by the source walk (and counted there) and then claimed here
	// as well. Target.FilesScanned is therefore an upper bound on the files that
	// were looked at, not a census. It is an informational field and no decision
	// reads it, so the overlap is left in place rather than deduplicated: the
	// exact per-arm numbers are files_count and
	// scan_metadata.binary.files_count, and a deduplication pass would need the
	// claimed paths to stay comparable across both arms.
	report.FilesCount += res.Summary.FilesCount

	claimed := make(map[string]bool, len(res.Claimed))
	for _, p := range res.Claimed {
		claimed[cleanAbs(p)] = true
	}

	kept := make([]Finding, 0, len(report.Findings)+len(res.Findings))
	for _, f := range report.Findings {
		if f.Engine != EngineNameBinary && claimed[cleanAbs(f.File)] {
			continue
		}
		kept = append(kept, f)
	}
	kept = append(kept, res.Findings...)

	sortFindings(kept)
	report.Findings = kept

	// The same function the source-only path uses, so the pass decision has one
	// implementation rather than two that agree today.
	recomputeReportPassed(report, false)
}
